import csv
import datetime as dt
import html
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from read_requests import Accounts, AUTH  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROFILES = [('Honda workshops', 'data'), ('Canon', 'data/canon')]
# the units the hub expects but has no Tally exports for yet
UNITS_TO_COME = [
    ('HSC Statue, Thiruvananthapuram (Honda)', 'Sales registers FY 2025-26 and 2026-27 to date, and stock summaries'),
    ('Head workshop, Nagercoil (Honda)', 'Sales registers FY 2025-26 and 2026-27 to date, and stock summaries'),
    ('Royal Enfield and Nissan', 'Sales and service registers, when ready'),
]


def month_end(today):
    """The last day of the month before `today`."""
    return today.replace(day=1) - dt.timedelta(days=1)


def rows(path):
    try:
        with open(os.path.join(ROOT, path), newline='', encoding='utf-8') as f:
            return list(csv.DictReader(f))
    except OSError:
        return []


def due(today):
    """[(group, unit name, [missing items])] for units with something outstanding."""
    end = month_end(today)
    label = end.strftime('%d %b %Y').lstrip('0')
    out = []
    for group, base in PROFILES:
        pending = {}
        for r in rows(f'{base}/completeness.csv'):
            if r.get('status', '').lower() != 'received':
                pending.setdefault(r['company'], []).append(r['file'])
        for c in rows(f'{base}/companies.csv'):
            items = []
            last = dt.date.fromisoformat(c['register_to']) if c.get('register_to') else None
            if not last or last < end:
                start = (last + dt.timedelta(days=1)) if last else end.replace(day=1)
                items.append(f'Sales register {start.strftime("%d %b").lstrip("0")} to {label}')
                items.append(f'Stock summary as at {label}')
            items += [p for p in pending.get(c['company'], []) if p not in items]
            if items:
                out.append((group, f"{c['name']} ({c['company']})", items))
    return end, out


