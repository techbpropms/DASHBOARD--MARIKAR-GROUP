#!/usr/bin/env python3
"""Builds the monthly "Tally files due" e-mail for the hub's administrators.

    python3 scripts/upload_reminder.py --out docs/mail/_upload-reminder.html     # writes the e-mail, prints the recipients

Each month the hub needs, from every unit, the sales register up to the end of the month just closed and the
stock summary as at that date. The list comes from the committed summaries only (data/companies.csv and
data/completeness.csv for each profile): a unit whose register stops short of the month end, a stock summary not
yet received, and the pending items the completeness tables already record. Units not yet on Tally data are listed
from UNITS_TO_COME. The "Upload reminder" workflow sends the result with scripts/send_mail.py to every super admin
and admin (their user IDs are printed on the last line).
"""
