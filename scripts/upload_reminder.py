def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    ap.add_argument('--today', help='YYYY-MM-DD, for a test (default: today)')
    args = ap.parse_args()
    today = dt.date.fromisoformat(args.today) if args.today else dt.date.today()
    month, page = render(today)
    with open(args.out, 'w', encoding='utf-8') as f:
        f.write(page)
    admins = [u['id'] for u in Accounts(AUTH).list() if u['role'] in ('admin', 'superadmin')]
    print(f'Tally files due for {month}')
    print(','.join(admins))


if __name__ == '__main__':
    main()
